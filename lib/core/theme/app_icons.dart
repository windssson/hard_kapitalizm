abstract final class AppIconSizes {
  // Changes every icon size while preserving the shared scale.
  static const double scale = 1.0;

  static double _scaled(double size) => (size * scale).sp;

  static double get xxSmall => _scaled(10);
  static double get xSmall => _scaled(12);
  static double get small => _scaled(14);
  static double get compact => _scaled(16);
  static double get regular => _scaled(18);
  static double get medium => _scaled(20);
  static double get mediumLarge => _scaled(22);
  static double get large => _scaled(24);
  static double get xLarge => _scaled(28);
  static double get display => _scaled(32);
  static double get displayLarge => _scaled(40);
  static double get hero => _scaled(48);
  static double get emptyState => _scaled(64);
  static double get showcase => _scaled(80);
}
